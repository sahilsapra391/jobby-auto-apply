#!/usr/bin/env python3
"""Copy the dashboard renderer into the isolated Vercel function bundle."""

from pathlib import Path
import shutil


REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "scripts"
TARGET = REPO / "deploy" / "renderer"
FILES = (
    "ats_match.py",
    "brand.py",
    # dashboard.py and found_lane.py both import this; without it the deployed
    # function fails at import and every request 502s.
    "clock.py",
    "company_logos.py",
    "dashboard.py",
    "found_lane.py",
    "jobs_store.py",
    "match_score.py",
    "premium_ui.py",
    # jobs_store imports this for the pool write lock. The deployed function
    # only ever reads, so it never takes the lock -- but the import happens at
    # module load, and a missing module 502s every request.
    "runlock.py",
    "search_config.py",
    "settings_panel.py",
    "state_slim.py",
    "store.py",
)
BRAND_ASSETS = (
    "01-favicon/favicon.svg",
    # favicon_links() inlines these two as data URIs, so they have to travel in
    # the function bundle. deploy/public/ holds copies, but Vercel turns that
    # directory into static edge output and drops it from the lambda, so a
    # bundle without them renders locally and 502s on every deployed request.
    "01-favicon/favicon.ico",
    "01-favicon/apple-touch-icon.png",
    "03-mark/jobby-mark-ink.svg",
    "04-lockup/jobby-lockup-horizontal-ink.svg",
    "06-mascot/jobby-mascot-lineart.svg",
)


def sync():
    """Copy source into the bundle, content only.

    shutil.copyfile deliberately does not carry the mode across, and that is
    right: ats_match.py, dashboard.py and store.py are 100755 in scripts/
    because they have CLI entry points, while the bundle copies are imported by
    the Vercel function and never executed. So the copies are 100644 and always
    will be.

    The trap that sets is `git diff main:scripts/X main:deploy/renderer/X`,
    which reports those three as changed on the mode alone: "1 file changed,
    0 insertions(+), 0 deletions(-)". Anyone reaching for that as a staleness
    check gets three false positives out of twelve. Compare blob hashes, or do
    what CI does and re-run this script and read git status.
    """
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / "__init__.py").write_text(
        '"""Deployment copy of the dashboard renderer. Generated by sync_vercel_renderer.py."""\n',
        encoding="utf-8",
    )
    for name in FILES:
        shutil.copyfile(SOURCE / name, TARGET / name)
    for name in BRAND_ASSETS:
        source = REPO / "assets" / "brand" / name
        target = REPO / "deploy" / "assets" / "brand" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)


if __name__ == "__main__":
    sync()
