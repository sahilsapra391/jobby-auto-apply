#!/usr/bin/env python3
"""Copy the dashboard renderer into the isolated Vercel function bundle."""

from pathlib import Path
import shutil


REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "scripts"
TARGET = REPO / "deploy" / "renderer"
FILES = (
    "ats_match.py",
    "brand.py",
    "company_logos.py",
    "dashboard.py",
    "found_lane.py",
    "jobs_store.py",
    "match_score.py",
    "premium_ui.py",
    "search_config.py",
    "settings_panel.py",
    "store.py",
)
BRAND_ASSETS = (
    "01-favicon/favicon.svg",
    "03-mark/jobby-mark-ink.svg",
    "04-lockup/jobby-lockup-horizontal-ink.svg",
    "06-mascot/jobby-mascot-lineart.svg",
)


def sync():
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / "__init__.py").write_text(
        '"""Deployment copy of the dashboard renderer. Generated by sync_vercel_renderer.py."""\n',
        encoding="utf-8",
    )
    for name in FILES:
        shutil.copyfile(SOURCE / name, TARGET / name)
    for name in BRAND_ASSETS:
        source = REPO / "assets" / "brand" / name
        target = REPO / "deploy" / "assets" / "brand" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)


if __name__ == "__main__":
    sync()
